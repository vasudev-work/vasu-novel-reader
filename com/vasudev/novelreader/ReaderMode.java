    private ReaderMode() {
    }

    public static boolean isOn(android.content.Context c) {
        try {
            return c.getSharedPreferences("ui", 0).getBoolean("readerMode", true);
        } catch (Exception e) {
            return true;
        }
    }

    public static void install(android.webkit.WebView view) {
        try {
            if (view == null) {
                return;
            }
            view.evaluateJavascript("window.__vasuCSS=" + jsString(CSS) + ";"
                    + "window.__vasuHTML=" + jsString(HTML) + ";"
                    + initScript(view.getContext()), null);
            view.evaluateJavascript(JS, null);
        } catch (Exception ignored) {
        }
    }

    private static String jsString(String s) {
        StringBuilder b = new StringBuilder("\"");
        for (int i = 0; i < s.length(); i++) {
            char ch = s.charAt(i);
            if (ch == '\\') {
                b.append("\\\\");
            } else if (ch == '"') {
                b.append("\\\"");
            } else if (ch == '\n') {
                b.append("\\n");
            } else if (ch == '\r') {
                continue;
            } else if (ch == '<') {
                b.append("\\u003c");
            } else {
                b.append(ch);
            }
        }
        return b.append("\"").toString();
    }

    /** The app's typography settings + the engines actually installed here. */
    private static String initScript(android.content.Context c) {
        try {
            android.content.SharedPreferences p =
                    c.getSharedPreferences("ui", android.content.Context.MODE_PRIVATE);
            int font = Math.max(0, Math.min(4, p.getInt("fontIdx", 4)));
            int pct = p.getInt("textSize", 100);
            int size = Math.max(13, Math.min(30, Math.round(17f * pct / 100f)));
            int line = 1;
            int lh = p.getInt("lineHeight", 160);
            if (lh < 150) {
                line = 0;
            } else if (lh > 190) {
                line = 2;
            }
            int rt = p.getInt("readerTheme", 0);
            int theme = rt >= 1 ? Math.min(5, rt - 1) : 3;
            boolean hl = p.getBoolean("highlightPara", true);
            boolean auto = p.getBoolean("autoAdvance", false);
            double rate = p.getFloat("readRate", 1.0f);
            return String.format(java.util.Locale.US,
                    "window.__vasuInit={font:%d,size:%d,line:%d,theme:%d,hl:%b,auto:%b,rate:%.2f,engines:%s};",
                    font, size, line, theme, hl, auto, rate, engineList(c));
        } catch (Exception e) {
            return "window.__vasuInit=null;";
        }
    }

    private static String engineList(android.content.Context c) {
        char q = (char) 34;
        try {
            java.util.List<android.content.pm.ResolveInfo> ris = c.getPackageManager()
                    .queryIntentServices(new android.content.Intent("android.intent.action.TTS_SERVICE"), 0);
            StringBuilder sb = new StringBuilder("[");
            if (ris != null) {
                for (android.content.pm.ResolveInfo ri : ris) {
                    if (ri.serviceInfo == null) {
                        continue;
                    }
                    CharSequence lbl = ri.loadLabel(c.getPackageManager());
                    String nm = lbl == null ? ri.serviceInfo.packageName : lbl.toString();
                    if (sb.length() > 1) {
                        sb.append(',');
                    }
                    sb.append('{').append(q).append("name").append(q).append(':').append(q)
                      .append(nm.replace(String.valueOf(q), "")).append(q)
                      .append(',').append(q).append("pkg").append(q).append(':').append(q)
                      .append(ri.serviceInfo.packageName).append(q).append('}');
                }
            }
            return sb.append(']').toString();
        } catch (Exception e) {
            return "[]";
        }
    }

